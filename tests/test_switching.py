"""Tests for the switching-option mine (Brennan and Schwartz 1985 replication)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import yaml

from pricedin.switching import (
    SwitchingMine,
    fixed_output_value,
    price_paths,
    spline_basis,
    value_switching_mine,
)

ROOT = Path(__file__).resolve().parents[1]
BENCHMARK = yaml.safe_load(
    (ROOT / "data" / "benchmarks" / "brennan_schwartz_1985.yaml").read_text(encoding="utf-8")
)
MINE = SwitchingMine(**BENCHMARK["parameters"])


def test_parameters_match_the_defaults() -> None:
    assert SwitchingMine() == MINE


def test_simulated_fixed_output_matches_closed_form() -> None:
    """Payoffs and discounting: operate every period, compare with the exact value."""
    dt, spot = 0.2, 0.8
    n_inv = 75
    x = price_paths(MINE, spot, n_inv, dt, 100_000, seed=3)
    total = np.zeros(x.shape[0])
    for j in range(n_inv):
        t = j * dt
        cost = MINE.average_cost * np.exp(MINE.cost_inflation * t)
        profit = MINE.output_rate * (x[:, j] - cost)
        flow = (profit - MINE.income_tax * np.maximum(profit, 0.0)) * dt
        total += flow * np.exp(-(MINE.interest_rate + MINE.property_tax) * t)
    sim = total / 1e6
    se = sim.std(ddof=1) / np.sqrt(sim.size)
    assert abs(sim.mean() - fixed_output_value(MINE, spot)) < 4 * se


def test_options_add_value_over_fixed_output() -> None:
    res = value_switching_mine(MINE, 0.5, n_paths=4_000, seed=5)
    assert res.open_value > fixed_output_value(MINE, 0.5)


def test_replicates_brennan_schwartz_at_one_price() -> None:
    """The full table is regenerated by scripts/brennan_schwartz.py (40,000 paths)."""
    open_ref, closed_ref = BENCHMARK["values"][0.5]
    res = value_switching_mine(MINE, 0.5, n_paths=10_000, seed=1)
    assert abs(res.open_value - open_ref) < 3 * res.open_se
    assert abs(res.closed_value - closed_ref) < 3 * res.closed_se


def test_closing_is_optimal_at_a_low_price() -> None:
    """At US$0.30 the open mine closes at once: its value is the closed value less the cost."""
    res = value_switching_mine(MINE, 0.3, n_paths=4_000, seed=2)
    assert res.open_value == pytest.approx(res.closed_value - MINE.closing_cost / 1e6, abs=1e-9)


def test_spline_basis_shape() -> None:
    u = np.linspace(-1.0, 1.0, 101)
    assert spline_basis(u, 5).shape == (101, 7)


def test_odd_paths_rejected() -> None:
    with pytest.raises(ValueError, match="even"):
        price_paths(MINE, 1.0, 3, 0.2, 7, seed=0)
